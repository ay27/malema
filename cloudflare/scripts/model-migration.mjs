import { readFileSync, writeFileSync } from 'node:fs';
const catalog = JSON.parse(readFileSync(new URL('../../model-catalog.json', import.meta.url)));
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const pairs = Object.entries(catalog.models).flatMap(([canonical, aliases]) => aliases.map(alias => `(${quote(alias)},${quote(canonical)})`));
const fields = [['full_contributions','cells'], ['contributions','cells'], ['snapshots','entries'], ['legacy_archive','entries']];
const originals = fields.map(([table, column]) => `SELECT DISTINCT json_extract(value,'$.model') AS original FROM ${table}, json_each(${table}.${column})`).join('\nUNION\n');
let sql = `-- Generated by scripts/model-migration.mjs from the public catalog.
-- Remove original routing labels from all current and legacy business tables.
-- Counts and contribution revisions are preserved.
CREATE TABLE _public_model_aliases (alias TEXT NOT NULL, canonical TEXT NOT NULL);
INSERT INTO _public_model_aliases VALUES\n${pairs.join(',\n')};
CREATE TABLE _public_model_map (original TEXT PRIMARY KEY, public TEXT NOT NULL);
INSERT INTO _public_model_map
WITH RECURSIVE originals AS (${originals}),
names AS (
 SELECT original, lower(replace(replace(trim(original),'_','-'),' ','-')) AS n FROM originals
), positions(p) AS (
 VALUES(1) UNION ALL SELECT p+1 FROM positions WHERE p < (SELECT coalesce(max(length(n)),0) FROM names)
), matches AS (
 SELECT original, canonical, p AS start, p+length(alias)-1 AS finish FROM names, positions, _public_model_aliases
 WHERE length(n)<=1024 AND n NOT GLOB '*[^ -~]*' AND instr(n,char(0))=0
 AND substr(n,p,length(alias))=alias
 AND (p=1 OR substr(n,p-1,1) NOT GLOB '[a-z0-9]')
 AND substr(n,p+length(alias),1) NOT GLOB '[a-z0-9]'
 AND (NOT (substr(n,p+length(alias),1) IN ('.','-') AND substr(n,p+length(alias)+1,1) GLOB '[0-9]')
 OR (substr(n,p+length(alias),1)='-' AND (
 (substr(n,p+length(alias)+1,8) GLOB '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]' AND substr(n,p+length(alias)+9,1) IN ('','-'))
 OR (substr(n,p+length(alias)+1,4) GLOB '[0-9][0-9][0-9][0-9]' AND substr(n,p+length(alias)+5,1) IN ('','-')))))
), best AS (
 SELECT a.* FROM matches a WHERE NOT EXISTS (
 SELECT 1 FROM matches b WHERE a.original=b.original AND b.start<=a.start AND b.finish>=a.finish AND b.finish-b.start>a.finish-a.start
 )
)
SELECT names.original, CASE WHEN count(DISTINCT best.canonical)=1 THEN min(best.canonical) ELSE 'other' END
FROM names LEFT JOIN best ON best.original=names.original GROUP BY names.original;
`;
for (const [table,column] of fields) sql += `
UPDATE ${table} SET ${column}=(
 SELECT json_group_array(json_object(
 'harness',CASE WHEN json_extract(value,'$.harness') IN ('codex','claude','deepseek','workbuddy','cursor','pi') THEN json_extract(value,'$.harness') ELSE 'other' END,
 'model',coalesce((SELECT public FROM _public_model_map WHERE original=json_extract(value,'$.model')),'other'),
 'language',json_extract(value,'$.language'),'turns',json_extract(value,'$.turns'),'hits',json_extract(value,'$.hits')))
 FROM json_each(${table}.${column})
);
`;
sql += '\nDROP TABLE _public_model_map;\nDROP TABLE _public_model_aliases;\n';
const output = new URL('../migrations/0003_public_model_names.sql', import.meta.url);
if (process.argv.includes('--check')) {
 if (readFileSync(output,'utf8') !== sql) throw new Error('Public model migration differs from the catalog');
} else writeFileSync(output,sql);
